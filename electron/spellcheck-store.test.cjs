const test = require('node:test')
const assert = require('node:assert/strict')
const { mkdtemp, readFile, writeFile, readdir, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { createSpellcheckStore } = require('./spellcheck-store.cjs')
test('personal dictionary serializes edits, survives restart, preserves corrupt input and validates imports', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'vietlatex-spelling-'))
  try {
    const store = createSpellcheckStore(directory)
    assert.deepEqual(await store.load(), { words: [], revision: 0 })
    await Promise.all([store.mutate('add', 'VietLaTeX'), store.mutate('add', 'quasifrobnicator')])
    assert.deepEqual((await createSpellcheckStore(directory).load()).words, ['VietLaTeX', 'quasifrobnicator'])
    await store.mutate('remove', 'VietLaTeX')
    assert.deepEqual((await store.load()).words, ['quasifrobnicator'])
    const before = await readFile(join(directory, 'spellcheck-v1.json'), 'utf8')
    await assert.rejects(store.mutate('merge', ['unsafe/S']))
    assert.equal(await readFile(join(directory, 'spellcheck-v1.json'), 'utf8'), before)
    await writeFile(join(directory, 'spellcheck-v1.json'), '{broken', 'utf8')
    const recovery = await store.load()
    assert.deepEqual(recovery.words, []); assert.ok(recovery.warning)
    assert.ok((await readdir(directory)).some(name => name.includes('.damaged-')))
    await store.mutate('add', 'VietLaTeX')
    assert.deepEqual((await store.load()).words, ['VietLaTeX'])
  } finally { assert.ok(directory.startsWith(join(tmpdir(), 'vietlatex-spelling-'))); await rm(directory, { recursive: true, force: true }) }
})
