/* global document, window */
import assert from 'node:assert/strict'
import {chromium} from 'playwright'
import {createServer} from 'vite'
import {mkdir} from 'node:fs/promises'
import {createProject,createTask} from '../src/services/WorkspaceData.js'
const server=await createServer({server:{host:'127.0.0.1',port:0}})
await server.listen()
await mkdir('artifacts/noir-audit',{recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true})
try{
 const page=await browser.newPage({viewport:{width:1366,height:660}})
 page.setDefaultTimeout(10000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const doc={type:'doc',content:[{type:'paragraph',content:[{type:'text',text:'Bản thảo kiểm tra giao diện với nhiều tài liệu.'}]}]}
 const project=createProject('Dự án kiểm tra',createTask('Tài liệu có tên rất dài để kiểm tra bố cục và khả năng thao tác',doc))
 for(let i=0;i<19;i++)project.tasks.push(createTask(`Tài liệu ${i+2} — tên dài để kiểm tra tab`,doc))
 await page.addInitScript(data=>{localStorage.setItem('latex-workspace-v1',JSON.stringify(data));localStorage.setItem('latex-pdf-batch-mode','manual')},{version:1,projects:[project],activeProjectId:project.id,mode:'split',activeTab:'write',pdfMode:'manual'})
 await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`)
 await page.locator('.tiptap').waitFor()
 for(const width of [1600,1366,1120,901,768,390]){
  console.log(`Auditing ${width} x 660`)
  await page.setViewportSize({width,height:660})
  for(const [tab,button] of [['Trang chủ','Màu chữ'],['Trang chủ','Tô sáng văn bản'],['Chèn','Chèn bảng'],['Chèn','Chèn ký tự đặc biệt']]){
   const tabButton=page.getByRole('button',{name:tab,exact:true});if(await tabButton.getAttribute('aria-expanded')!=='true')await tabButton.click()
   const trigger=page.getByRole('button',{name:button,exact:true});await trigger.click()
   const menu=page.locator('.studio-menu'),box=await menu.boundingBox(),anchor=await trigger.boundingBox()
   assert.ok(box.x>=7&&box.x+box.width<=width-7,`${button} horizontal bounds ${width}`)
   assert.ok(box.y>=7&&box.y+box.height<=660-7,`${button} vertical bounds ${width}`)
   assert.ok(Math.abs(anchor.y-box.y-box.height-6)<2,`${button} follows trigger ${width}`)
   await page.keyboard.press('Escape')
   assert.equal(await menu.count(),0)
   assert.equal(await trigger.evaluate(el=>el===document.activeElement),true)
   assert.equal(await tabButton.getAttribute('aria-expanded'),'true')
  }
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
  await page.locator('.tiptap').click()
  await page.keyboard.press('Control+f')
  await page.getByRole('textbox',{name:'Tìm trong bản thảo',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('textbox',{name:'Tìm trong bản thảo',exact:true}).count(),0)
  await page.locator('.tiptap').focus()
  await page.keyboard.press('Control+f')
  await page.getByRole('textbox',{name:'Tìm trong bản thảo',exact:true}).waitFor()
  await page.getByRole('button',{name:'Đóng tìm kiếm',exact:true}).click()
  assert.equal(await page.getByRole('textbox',{name:'Tìm trong bản thảo',exact:true}).count(),0)
  const tab=page.getByRole('button',{name:'Chèn',exact:true});if(await tab.getAttribute('aria-expanded')!=='true')await tab.click()
  await page.getByRole('button',{name:'Chèn liên kết (Ctrl+Shift+K)',exact:true}).click()
  await page.getByRole('textbox',{name:'Địa chỉ liên kết',exact:true}).focus()
  await page.keyboard.press('Escape')
  assert.equal(await page.getByRole('textbox',{name:'Địa chỉ liên kết',exact:true}).count(),0)
  await page.screenshot({path:`artifacts/noir-audit/width-${width}.png`})
 }
 await page.setViewportSize({width:1366,height:768})
 await page.getByRole('button',{name:'Soạn + PDF',exact:true}).waitFor()
 await page.waitForTimeout(200)
 const insertTab=page.getByRole('button',{name:'Chèn',exact:true})
 if(await insertTab.getAttribute('aria-expanded')!=='true')await insertTab.click()
 await page.getByRole('button',{name:'Chèn bảng',exact:true}).click()
 await page.setViewportSize({width:1120,height:660})
 const menuBox=await page.locator('.studio-menu').boundingBox(),anchorBox=await page.getByRole('button',{name:'Chèn bảng',exact:true}).boundingBox()
 assert.ok(Math.abs(anchorBox.y-menuBox.y-menuBox.height-6)<2,'open menu follows viewport resize')
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'Sắp xếp và tổng hợp tab',exact:true}).click()
 await page.locator('.project-tab-option').last().scrollIntoViewIfNeeded()
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
 await page.getByRole('button',{name:'Sắp xếp và tổng hợp tab',exact:true}).click()
 await page.setViewportSize({width:390,height:660})
 await page.waitForTimeout(200)
 await page.getByRole('tab',{name:'Tài liệu có tên rất dài để kiểm tra bố cục và khả năng thao tác',exact:true}).dblclick()
 await page.getByRole('textbox',{name:'Tên tab',exact:true}).fill('A'.repeat(160))
 const rename=await page.locator('.project-tab-rename').boundingBox()
 const renameInput=await page.getByRole('textbox',{name:'Tên tab',exact:true}).boundingBox()
 assert.ok(renameInput.x+renameInput.width<=rename.x+rename.width,'rename form stays inside panel')
 await page.getByRole('button',{name:'Hủy',exact:true}).click()
 await page.setViewportSize({width:390,height:420})
 await page.getByRole('button',{name:'Quản lý tài liệu',exact:true}).click()
 const manager=page.getByRole('dialog')
 for(const label of ['Tài liệu','Trang & tác giả','Tài nguyên','Học thuật']){
  await manager.getByRole('button',{name:label,exact:true}).click()
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth))
  const closeBox=await manager.getByRole('button',{name:'Đóng',exact:true}).boundingBox()
  assert.ok(closeBox.y>=0&&closeBox.y+closeBox.height<=420,'manager close stays visible')
  const body=await manager.locator('.studio-manager-body').boundingBox(),dialog=await manager.boundingBox()
  assert.ok(body.y+body.height<=dialog.y+dialog.height+1,'manager body remains scrollable inside short window')
 }
 await manager.getByRole('button',{name:'Đóng',exact:true}).click()
 assert.deepEqual(errors,[])
 console.log('Noir audit passed: 20 tabs, long titles, six short-window widths, four anchored menus, keyboard focus, resize, find/link close and tab options.')
}finally{await browser.close();await server.close()}
