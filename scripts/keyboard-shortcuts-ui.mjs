/* global document, KeyboardEvent */
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import { createServer } from 'vite'
import { createProject, createTask } from '../src/services/WorkspaceData.js'

const output = 'artifacts/keyboard-shortcuts'
await mkdir(output, { recursive: true })
const server = await createServer({ server: { host: '127.0.0.1', port: 0 } })
await server.listen()
const origin = `http://127.0.0.1:${server.httpServer.address().port}`
let browser
const results = []
try {
  browser = await chromium.launch({ headless: true })
  for (const [platform, primary, label] of [['Win32', 'Control', 'Ctrl'], ['MacIntel', 'Meta', '⌘']]) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    const project = createProject('Kiểm tra phím tắt', createTask('Bản thảo phím tắt', { type: 'doc', content: [{ type: 'paragraph' }] }))
    await page.addInitScript(({ platform, project }) => {
      Object.defineProperty(navigator, 'platform', { get: () => platform })
      Object.defineProperty(navigator, 'userAgentData', { get: () => ({ platform: platform === 'MacIntel' ? 'macOS' : 'Windows' }) })
      localStorage.setItem('latex-workspace-v1', JSON.stringify({ version: 1, projects: [project], activeProjectId: project.id, mode: 'write', activeTab: 'write', latexOpen: true }))
      localStorage.setItem('latex-pdf-batch-mode', 'manual')
    }, { platform, project })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    page.setDefaultTimeout(10000)
    await page.goto(origin)
    const draft = page.locator('.tiptap')
    await draft.waitFor()
    assert.equal(await page.getByRole('button', { name: 'Cơ bản', exact: true }).count(), 0)
    assert.equal(await page.getByRole('button', { name: 'Trang chủ', exact: true }).count(), 1)
    await page.getByRole('button', { name: 'Soạn + PDF', exact: true }).click()
    assert.equal(await page.locator('.studio-drawer').count(), 0, 'old preferences do not recreate the duplicate source viewer')
    assert.equal(await page.getByRole('button', { name: 'Xem LaTeX', exact: true }).count(), 0)
    await page.getByRole('button', { name: 'Soạn thảo', exact: true }).click()
    await page.getByRole('button', { name: 'Tham chiếu', exact: true }).click()
    await page.getByRole('button', { name: 'Nhãn, tham chiếu chéo và chú thích', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Học thuật', exact: true }).waitFor()
    assert.equal(await page.getByRole('dialog').getByRole('button', { name: 'Học thuật', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Bố cục', exact: true }).click()
    await page.getByRole('button', { name: 'Thiết lập tài liệu, trang và tác giả', exact: true }).click()
    assert.equal(await page.getByRole('dialog').getByRole('button', { name: 'Trang & tác giả', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Trang chủ', exact: true }).click()
    const selectText = async () => { await draft.fill('Phím tắt học thuật'); await draft.press(`${primary}+a`) }
    await selectText()
    for (const [key, tag] of [['b', 'strong'], ['i', 'em'], ['u', 'u'], ['Shift+s', 's']]) {
      await page.keyboard.press(`${primary}+${key}`)
      assert.equal(await draft.locator(tag).innerText(), 'Phím tắt học thuật', `${platform}: ${key}`)
    }
    await page.keyboard.press(`${primary}+Shift+e`)
    assert.equal(await draft.locator('p').evaluate(node => node.style.textAlign), 'center')
    await page.keyboard.press(`${primary}+Backslash`)
    assert.equal(await draft.locator('strong,em,u,s').count(), 0)
    assert.equal(await draft.locator('p').evaluate(node => node.style.textAlign), '')
    for (const [key, tag] of [['Comma', 'sub'], ['Period', 'sup']]) {
      await page.keyboard.press(`${primary}+${key}`)
      assert.equal(await draft.locator(tag).innerText(), 'Phím tắt học thuật')
      await page.keyboard.press(`${primary}+${key}`)
      assert.equal(await draft.locator(tag).count(), 0, `${platform} toggle ${tag}: ${await draft.innerHTML()}`)
    }
    await page.keyboard.press(`${primary}+b`)
    await page.keyboard.press(`${primary}+z`)
    assert.equal(await draft.locator('strong').count(), 0)
    await page.keyboard.press(`${primary}+y`)
    assert.equal(await draft.locator('strong').innerText(), 'Phím tắt học thuật')
    await page.keyboard.press(`${primary}+Backslash`)
    await draft.press('ArrowLeft')
    for (const level of [1, 2, 3]) {
      await draft.press(`${primary}+Alt+${level}`)
      assert.equal(await draft.locator(`h${level}`).filter({ hasText: 'Phím tắt học thuật' }).count(), 1, `${platform}: heading ${level}`)
    }
    await draft.press(`${primary}+Alt+0`)
    assert.equal(await draft.locator('h1,h2,h3').count(), 0)
    for (const [key, tag] of [['8', 'ul'], ['7', 'ol']]) {
      await draft.locator('p').filter({ hasText: 'Phím tắt học thuật' }).click()
      await page.waitForFunction(() => document.querySelector('.tiptap').editor.state.selection.empty)
      await draft.press(`${primary}+Shift+${key}`)
      assert.equal(await draft.locator(tag).count(), 1)
      await draft.press(`${primary}+Shift+${key}`)
      assert.equal(await draft.locator(tag).count(), 0, `${platform} toggle ${tag}: ${await draft.innerHTML()}`)
    }
    for (const [key, align] of [['l', 'left'], ['e', 'center'], ['r', 'right'], ['j', 'justify']]) {
      await draft.press(`${primary}+Shift+${key}`)
      assert.equal(await draft.locator('p').first().evaluate(node => node.style.textAlign), align)
    }
    await selectText()
    await draft.press(`${primary}+Shift+k`)
    const link = page.getByRole('textbox', { name: 'Địa chỉ liên kết', exact: true })
    await link.waitFor()
    assert.equal(await link.evaluate(node => node === document.activeElement), true, 'link shortcut focuses the URL input')
    await link.fill('https://example.org')
    await link.press('Enter')
    assert.equal(await draft.locator('a').getAttribute('href'), 'https://example.org')
    await draft.press(`${primary}+k`)
    await page.getByRole('dialog', { name: 'Bảng lệnh', exact: true }).waitFor()
    await page.keyboard.press('Escape')
    await draft.press(`${primary}+f`)
    const find = page.getByRole('textbox', { name: 'Tìm trong bản thảo', exact: true })
    await find.waitFor()
    assert.equal(await find.evaluate(node => node === document.activeElement), true)
    await page.keyboard.press('Escape')
    await draft.press(platform === 'MacIntel' ? `${primary}+Alt+f` : `${primary}+h`)
    const replacement = page.getByRole('textbox', { name: 'Thay bằng', exact: true })
    await replacement.waitFor()
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Thay bằng')
    assert.equal(await replacement.evaluate(node => node === document.activeElement), true)
    await page.keyboard.press('Escape')
    await draft.press(`${primary}+Shift+m`)
    await page.getByRole('dialog', { name: 'Chèn công thức', exact: true }).waitFor()
    await page.getByRole('dialog').getByRole('button', { name: 'Đóng', exact: true }).click()
    await draft.press(`${primary}+Shift+c`)
    await page.getByRole('dialog').waitFor()
    await page.keyboard.press('Escape')
    await draft.press('End')
    await draft.press(`${primary}+Enter`)
    assert.equal(await draft.locator('[data-page-break]').count(), 1)

    // Caption inputs live inside the editor DOM but own their text editing.
    await draft.evaluate(node => { node.editor.commands.insertTable({ rows: 1, cols: 1, withHeaderRow: false }) })
    const caption = page.getByRole('textbox', { name: 'Tên bảng', exact: true })
    await caption.fill('Tên bảng kiểm tra')
    const beforeCaptionShortcut = await draft.evaluate(node => node.editor.getJSON())
    await caption.press(`${primary}+Shift+m`)
    assert.equal(await page.getByRole('dialog').count(), 0, 'caption input does not open the formula dialog')
    await caption.press(`${primary}+Backslash`)
    assert.deepEqual(await draft.evaluate(node => node.editor.getJSON()), beforeCaptionShortcut, 'caption input does not clear document formatting')

    const title = page.getByRole('textbox', { name: 'Tên tài liệu', exact: true })
    await title.fill('Lưu bằng bàn phím')
    await title.press(`${primary}+s`)
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('latex-workspace-v1')).projects[0].tasks[0].title === 'Lưu bằng bàn phím')
    const beforeDialog = await draft.evaluate(node => node.editor.getJSON())
    await title.press(`${primary}+b`)
    assert.deepEqual(await draft.evaluate(node => node.editor.getJSON()), beforeDialog, 'formatting in the title never changes the draft')
    const ribbonWasOpen = await page.getByRole('toolbar', { name: 'Công cụ soạn thảo', exact: true }).isVisible()
    await draft.press('F1')
    const help = page.getByRole('dialog', { name: 'Phím tắt', exact: true })
    await help.waitFor()
    const search = help.getByRole('searchbox', { name: 'Tìm phím tắt', exact: true })
    await search.fill('in dam')
    assert.equal(await help.locator('dt').count(), 1)
    assert.equal(await help.locator('kbd').innerText(), `${label}+B`)
    await search.press(`${primary}+k`)
    assert.equal(await page.getByRole('dialog', { name: 'Bảng lệnh', exact: true }).count(), 0)
    await search.press('F1')
    await help.waitFor({ state: 'detached' })
    assert.equal(await page.getByRole('toolbar', { name: 'Công cụ soạn thảo', exact: true }).isVisible(), ribbonWasOpen)
    const composingHandled = await draft.evaluate((node, primary) => node.dispatchEvent(new KeyboardEvent('keydown', { key: 'M', ctrlKey: primary === 'Control', metaKey: primary === 'Meta', shiftKey: true, isComposing: true, bubbles: true, cancelable: true })), primary)
    assert.equal(composingHandled, true)
    assert.equal(await page.getByRole('dialog').count(), 0)

    await page.getByRole('tab', { name: 'Tổng hợp', exact: true }).click()
    const summary = await draft.evaluate(node => node.editor.getJSON())
    await draft.press(`${primary}+b`)
    await draft.press(`${primary}+Shift+m`)
    assert.deepEqual(await draft.evaluate(node => node.editor.getJSON()), summary, 'read-only summary stays unchanged')
    assert.equal(await page.getByRole('dialog').count(), 0)
    await draft.press('F1')
    await help.waitFor()
    await page.screenshot({ path: `${output}/${platform}-desktop.png` })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: `${output}/${platform}-mobile.png` })
    const bounds = await help.boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 391 && bounds.y >= 0 && bounds.y + bounds.height <= 845, 'help fits a narrow screen')
    await page.keyboard.press('Escape')
    assert.deepEqual(errors, [])
    results.push({ platform, passed: true, formatting: true, applicationShortcuts: true, inputIsolation: true, readOnlyPreserved: true, responsiveHelp: true })
    await context.close()
  }
  await writeFile(`${output}/report.json`, JSON.stringify({ passed: true, results }, null, 2)+'\n')
  console.log(JSON.stringify({ passed: true, results }))
} finally {
  await browser?.close()
  await server.close()
}
